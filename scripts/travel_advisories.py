def summarize_clusters(df, cluster_col):
    summaries = []
    for cluster, group in df.groupby(cluster_col):
        summary = {
            'cluster': cluster,
            'count': len(group)
        }
        # Boolean features → proportion True
        for col in boolean_cols:
            summary[col] = group[col].mean() * 100  # % True

