import torch

edges = []
for _, row in borders_df.iterrows():
  src = country_to_idx.get(row['Country1'])
  dst = country_to_idx.get(row['Country2'])
  if src is not None and dst is not None:
    edges.append([src, dst])
    edges.append([dst, src]) # undirected graph

edge_index = torch.tensor(edges, dtype=torch.long).t().contiguous()
print(edge_index.shape) # should be [2, num_edges]

x = torch.tensor(attributes_df.values, dtype=torch.float)
print(x.shape)

from torch_geometric.data import Data

data = Data(x=x, edge_index=edge_index)
print(data)

import torch.nn as nn
from torch_geometric.nn import SAGEConv

class GraphSAGE(nn.Module):
    def __init__(self, in_channels, hidden_channels, out_channels):
        super().__init__()
        self.conv1 = SAGEConv(in_channels, hidden_channels)
        self.conv2 = SAGEConv(hidden_channels, out_channels)

    def forward(self, data):
        x, edge_index = data.x, data.edge_index
        x = self.conv1(x, edge_index)
        x = torch.relu(x)
        x = self.conv2(x, edge_index)
        return x

model = GraphSAGE(
 in_channels=data.num_node_features,
 hidden_channels=28,
 out_channels=13 # final embedding dimension
)

optimizer = torch.optim.Adam(model.parameters(), lr=0.01)
criterion = nn.MSELoss()

model.train()
for epoch in range(100):
 optimizer.zero_grad()
 out = model(data) # node embeddings
 loss = criterion(out, data.x) # reconstruct features
 loss.backward()
 optimizer.step()

if epoch % 10 == 0:
  print(f"Epoch {epoch}, Loss: {loss.item():.4f}")

model.eval()
with torch.no_grad():
  embeddings = model(data) # shape: [num_teams, 13]

